/**
 * 页面 / 抽屉 / 弹窗三种容器的归属规则（#1792，参考飞书项目；#1797 里 ForgQi 定为「层级 + 复杂度」）：
 * 层级：一层是侧栏入口页；二层是入口页里的对象，或它的附属内容；三层是对象的子项，或在浮层里发起的动作。
 * - 页面：侧栏入口页，以及列表里独立对象的完整编辑、整套配置（投稿模板、Fleet 配置），要能刷新、分享链接、浏览器后退；
 * - 右侧抽屉：列表里某一项的查看与编辑，以及附属于某个页面或对象的内容（节点覆盖、本机密钥、配置覆写），
 *   开在所在的页面上，背后的页面留作上下文；字段多就用 lg 档；
 * - 居中弹窗：一次性的短任务（不超过 5 个输入、确认、选择），做完回到原处；从抽屉里发起时也用弹窗。
 * 共同约定：页面最多两层（侧栏页 → 对象页）；抽屉里只再开弹窗，不开页面、不叠抽屉；弹窗里不再开任何东西。
 * 操作位置：
 * - 页面：主按钮在页头右上角（少数次要操作放在它左边）；没有「取消」，返回靠页头左侧的返回箭头；不套单体大卡片，分区用标题与分隔线；
 *   带 Tab 的配置页用 fill：内容占满页头下方，页面不滚、各面板自己滚；抽屉里的 Tab 同理（FormSheet 的 fill）；
 *   底栏状态在内容组件里的抽屉（发布切片）用 FormSheet 的 flush + SheetFooterBar，外观与自带底栏一致；
 * - 浮层（抽屉、弹窗）：底栏右下角「取消」+ 主按钮（实心；列表型抽屉的「+ 添加」用浅色带加号），「取消」只出现在浮层里；
 *   次要操作放底栏左侧；标题栏右侧只留关闭按钮；
 * - 主按钮写动作（创建模板 / 保存 / 添加…），不写「确定」。
 */

