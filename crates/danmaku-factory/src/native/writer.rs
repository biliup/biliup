//! Serialize the resolved layout. No occupancy or emission decisions live here.
use super::escape;
use super::layout::{Emission, LayoutedPool, Placement, SpecialFade, Style};
use crate::ConvertOptions;
use std::io::{self, Write};

struct PlatformWriter<W>(W);
impl<W: Write> Write for PlatformWriter<W> {
    fn write(&mut self, bytes: &[u8]) -> io::Result<usize> {
        if !cfg!(windows) {
            return self.0.write(bytes);
        }
        for part in bytes.split_inclusive(|&byte| byte == b'\n') {
            if let Some(body) = part.strip_suffix(b"\n") {
                self.0.write_all(body)?;
                self.0.write_all(b"\r\n")?;
            } else {
                self.0.write_all(part)?;
            }
        }
        Ok(bytes.len())
    }
    fn flush(&mut self) -> io::Result<()> {
        self.0.flush()
    }
}

fn time(mut output: impl Write, ms: i64) -> io::Result<()> {
    // printTime clamps nonpositive special end times to zero.
    let cs = ms.max(0) / 10;
    write!(
        output,
        "{}:{:02}:{:02}.{:02}",
        cs / 360000,
        cs / 6000 % 60,
        cs / 100 % 60,
        cs % 100
    )
}

fn color(mut value: i32) -> [u8; 6] {
    // Preserve even defined negative-color C remainder behavior at the raw
    // API; normalized business inputs are always RGB 0..=0xffffff.
    let mut output = [0; 6];
    for pair in 0..3 {
        for nibble in (0..2).rev() {
            let digit = value % 16;
            output[pair * 2 + nibble] = if digit < 10 {
                (digit + 48) as u8
            } else {
                (digit - 10 + 65) as u8
            };
            value /= 16;
        }
    }
    output
}

/// C's default %g precision is six significant digits, including exponent
/// thresholds after rounding. Rust formatting itself is locale independent.
fn general(value: f32) -> String {
    let scientific = format!("{:.5e}", f64::from(value));
    let (mantissa, exponent) = scientific.split_once('e').expect("scientific format");
    let exponent: i32 = exponent.parse().expect("formatted exponent");
    if !(-4..6).contains(&exponent) {
        let mantissa = mantissa.trim_end_matches('0').trim_end_matches('.');
        format!("{mantissa}e{exponent:+03}")
    } else {
        let fixed = format!("{:.*}", (5 - exponent).max(0) as usize, f64::from(value));
        if fixed.contains('.') {
            fixed.trim_end_matches('0').trim_end_matches('.').to_owned()
        } else {
            fixed
        }
    }
}

fn placement(mut output: impl Write, placement: Placement) -> io::Result<()> {
    match placement {
        Placement::Position { x, y } => write!(output, "\\pos({x},{y})"),
        Placement::Move {
            from_x,
            from_y,
            to_x,
            to_y,
            timing,
        } => {
            write!(output, "\\move({from_x},{from_y},{to_x},{to_y}")?;
            if let Some(timing) = timing {
                write!(output, ",{},{}", timing.start_ms, timing.end_ms)?;
            }
            output.write_all(b")")
        }
        Placement::None => Ok(()),
    }
}

pub(crate) fn write(
    output: impl Write,
    events: &LayoutedPool,
    options: &ConvertOptions,
) -> io::Result<()> {
    let mut output = PlatformWriter(output);
    if cfg!(windows) {
        output.write_all(b"\xef\xbb\xbf")?;
    }
    write!(
        output,
        "[Script Info]\n; Script generated by DanmakuFactory v1.70\n; https://github.com/hihkm/DanmakuFactory/\nScriptType: v4.00+\nCollisions: Normal\nPlayResX: {}\nPlayResY: {}\nTimer: 100.0000\nWrapStyle: 2\nScaledBorderAndShadow: yes\n\n[V4+ Styles]\nFormat: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n",
        options.width, options.height
    )?;
    for style in ["R2L", "L2R", "TOP", "BTM", "SP", "MSG"] {
        let special = matches!(style, "SP" | "MSG");
        let msg = style == "MSG";
        let font_size = if msg { 38 } else { options.font_size };
        let outline = if msg {
            options.outline * 38.0 / options.font_size as f32
        } else {
            options.outline
        };
        let shadow = if msg {
            options.shadow * 38.0 / options.font_size as f32
        } else {
            options.shadow
        };
        write!(
            output,
            "\nStyle: {style},{},{font_size},&H{:02X}FFFFFF,&H00FFFFFF,&H{:02X}000000,&H1E6A5149,{},0,0,0,100.00,100.00,0.00,0.00,1,{:.1},{:.1},{},0,0,0,1",
            options.font_name,
            if special { 0 } else { 255 - options.opacity },
            255 - options.outline_opacity,
            u8::from(options.bold),
            f64::from(outline),
            f64::from(shadow),
            if special { 7 } else { 8 }
        )?;
    }
    output.write_all(b"\n\n[Events]\nFormat: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text")?;
    for (index, record) in events.iter().enumerate() {
        let event = record.resolved();
        if event.emission == Emission::Omit {
            continue;
        }
        if event.style == Style::Code {
            write!(
                output,
                "\nComment: NO.{}(Code danmaku):Unable to read this type.",
                index + 1
            )?;
            continue;
        }
        if event.style == Style::Unknown {
            write!(output, "\nComment: NO.{}:unknow type", index + 1)?;
            continue;
        }
        write!(
            output,
            "\n{}: {},",
            if event.emission == Emission::Dialogue {
                "Dialogue"
            } else {
                "Comment"
            },
            event.layer
        )?;
        time(&mut output, event.start_ms)?;
        output.write_all(b",")?;
        time(&mut output, event.end_ms)?;
        let style = match event.style {
            Style::RightToLeft => "R2L",
            Style::LeftToRight => "L2R",
            Style::Top => "TOP",
            Style::Bottom => "BTM",
            Style::Special => "SP",
            _ => unreachable!("handled metadata comment"),
        };
        write!(output, ",{style},,0000,0000,0000,,{{")?;
        placement(&mut output, event.placement)?;
        if let Some(size) = event.font_size_override {
            write!(output, "\\fs{size}")?;
        }
        if event.blur {
            write!(output, "\\blur{}", general(events.blur))?;
        }
        if let Some(special) = event.special {
            if record.color() != 0xffffff {
                output.write_all(b"\\c&H")?;
                output.write_all(&color(record.color()))?;
            }
            if special.rotation_y != 0 {
                write!(output, "\\fry{}", special.rotation_y)?;
            }
            if special.rotation_z != 0 {
                write!(output, "\\frz{}", special.rotation_z)?;
            }
            match special.fade {
                SpecialFade::Opaque => output.write_all(b"\\alpha&H00")?,
                SpecialFade::Transition {
                    start,
                    end,
                    transition_start_ms,
                    transition_end_ms,
                } => write!(
                    output,
                    "\\fade({start},{start},{end},0,0,{transition_start_ms},{transition_end_ms})"
                )?,
            }
            if !special.font_name.is_empty() {
                write!(output, "\\fn{}", special.font_name)?;
            }
            output.write_all(b"}")?;
            output.write_all(record.text.as_bytes())?;
        } else {
            output.write_all(b"}")?;
            if record.color() != 0xffffff {
                output.write_all(b"{\\c&H")?;
                output.write_all(&color(record.color()))?;
                output.write_all(b"}")?;
            }
            escape::write_ordinary(&mut output, &record.text)?;
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn c_numeric_format_and_color_contracts() {
        for (value, expected) in [
            (0., "0"),
            (2.5, "2.5"),
            (100., "100"),
            (0.0001, "0.0001"),
            (0.00001, "1e-05"),
            (1.2345678, "1.23457"),
            (0.9999999, "1"),
        ] {
            assert_eq!(general(value), expected);
        }
        assert_eq!(&color(0x123456), b"563412");
        assert_eq!(&color(-1), b"0/0000");
        let mut output = Vec::new();
        time(&mut output, 1_800_000_010).unwrap();
        assert_eq!(output, b"500:00:00.01");
    }

    #[test]
    fn serialization_follows_ir_without_modifying_layout_or_text() {
        use super::super::{layout, model, parse};
        let options = ConvertOptions {
            outline: 1.,
            outline_blur: 2.5,
            ..Default::default()
        };
        let mut source = parse::read(
            &b"<i><d p=\"1,1,25,16777215,0\">x</d></i>"[..],
            parse::Budget::RAW,
        )
        .unwrap();
        model::normalize_and_sort(&mut source, &options);
        let events = layout::layout(source, &options).unwrap();
        let before = events.clone();
        let altered_options = ConvertOptions {
            width: 64,
            height: 1,
            scroll_time: 0.01,
            outline_blur: 99.,
            ..options
        };
        let mut bytes = Vec::new();
        write(&mut bytes, &events, &altered_options).unwrap();
        let text = String::from_utf8(bytes).unwrap();
        assert!(
            text.contains(
                "Dialogue: 0,0:00:01.00,0:00:13.00,R2L,,0000,0000,0000,,{\\move(1935,0,-15,0)\\blur2.5}x"
            )
        );
        assert_eq!(events, before);
    }
}
